  // Looks up a string in the language, falls back to German, then to the key itself.
  function t(lang, key, vars) {
    const table = STRINGS[lang] || STRINGS.de;
    let s = Object.prototype.hasOwnProperty.call(table, key)
      ? table[key]
      : Object.prototype.hasOwnProperty.call(STRINGS.de, key) ? STRINGS.de[key] : key;
    if (vars) {
      for (const k of Object.keys(vars)) s = s.split('{' + k + '}').join(String(vars[k]));
    }
    return s;
  }

